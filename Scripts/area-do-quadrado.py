#salva o numero colocado pelo usuario em variaveis
h = int(input("Qual é o tamanho da haltura do quadrado: "))
b = int(input("Qual é o tamanho da base do quadrado: "))

#multiplica o numero das variaveis
a = h*b

#mostra o resultado para o usuario
print(f"o tamanho do quadrado de {h} haltura e com {b} de base tem uma área de {a}")