#salva o numero colocado pelo usuario em variaveis
h = int(input("Qual é o tamanho da haltura do triangulo: "))
b = int(input("Qual é o tamanho da base do triangulo"))

#multiplica o numero das variaveis e divide em 2
a = h*b/2

#mostra o resultado para o usuario
print(f"O tamanho do triangulo de {h} haltura e com {b} de base tem uma área de {a}")